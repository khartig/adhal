'use strict'

// Frozen vectors for the v2 handshake's parameter mapping: nameplate,
// secret, sid, both scalars and both capability sets in; generator, Ya, Yb,
// K, transcript, ISK, mac_key, both confirmations and both channel keys
// out. PROTOCOL.md section 11 asks for exactly this set.
//
// HONEST ABOUT WHAT THESE PROVE, because it is not the same thing
// cpace-vectors.test.js proves and conflating them would be the most
// misleading possible outcome of having both files.
//
// cpace-vectors.test.js transcribes draft-irtf-cfrg-cpace-14. Those values
// were computed by someone else, so they are an external acceptance
// criterion: if engine/src/cpace.js does not reproduce them it is wrong,
// and no amount of internal agreement rescues it.
//
// The values BELOW were generated by this implementation. They cannot show
// that the mapping is the one section 3.2 specifies -- only that it has not
// drifted since it was reviewed against section 3.2 by eye. That is worth
// having (a changed info string, a swapped ADa/ADb, a transcript built with
// the wrong lv_cat nesting, or k_r2s and k_s2r exchanged would each fail
// here and nowhere else) and it is not conformance.
//
// SO EVERY DERIVATION IS RECOMPUTED A SECOND WAY. The block at the bottom
// rebuilds the ISK, the MAC key, both confirmations and both channel keys
// from Node's own SHA-512, HMAC-SHA256 and HKDF over byte strings this file
// assembles by hand -- not by calling cpace.js's lvCat or handshake.js's
// deriveAll. Where correctness can be checked here rather than pinned, it
// is; the curve arithmetic is the part that cannot be, and that is what the
// CFRG vectors are for.

const test = require('node:test')
const assert = require('node:assert/strict')
const crypto = require('node:crypto')

const {
  calculateGenerator,
  generatorString,
  scalarMultVfy,
  transcriptIR,
  isk,
  channelIdentifier,
  associatedData,
  deriveAll,
  encodeCaps,
  VERSION
} = require('@quay/engine')

const hex = (b) => Buffer.from(b).toString('hex')
const utf8 = (s) => Buffer.from(s, 'utf8')

// One fully worked handshake. The scalars are fixed constants rather than
// sampled, which is the whole point of a vector -- and is also why nothing
// in the engine accepts an injected scalar: a caller that could supply one
// could reuse one (section 3.2 trap #1). This file reaches past
// Initiator/Responder to the primitives for that reason.
const V = {
  nameplate: 'acid-acorn',
  secret: 'acre-acts-afar',
  sid: '0123456789abcdef0123456789abcdef',
  ya: '1111111111111111111111111111111111111111111111111111111111111111',
  yb: '2222222222222222222222222222222222222222222222222222222222222222',

  // Asymmetric on purpose: the receiver offers both capabilities and the
  // sender only one, so a vector exists in which ADa and ADb differ. Equal
  // capability sets would let a swapped ADa/ADb pass unnoticed, which is
  // one of the two mistakes this file is here to catch.
  capsR: ['resume', 'stream'],
  capsS: ['resume'],

  CI: '07717561792d76320a616369642d61636f726e',
  ADa: '01020d726573756d652c73747265616d',
  ADb: '010206726573756d65',

  generator: '64616807323f979e5113b0d881e5fc2d0007ab6bebdba5bfbb04b11352d1776c',
  Ya: 'd4ca811e0738c042ec1800c2e9c340d88e23fabb7af89a5fd9279dead829a051',
  Yb: 'e3bd4d606be04b52e808cd6a2564e9343e649f09c92c21aa3d16af927ddfbc17',
  K: 'dea9dd3ad4a5decd71a3780c748083002ea433d0f899f7e4b70b8f9791323062',

  transcript:
    '20d4ca811e0738c042ec1800c2e9c340d88e23fabb7af89a5fd9279dead829a051' +
    '1001020d726573756d652c73747265616d' +
    '20e3bd4d606be04b52e808cd6a2564e9343e649f09c92c21aa3d16af927ddfbc17' +
    '09010206726573756d65',

  isk:
    '490c7571c3c06aa61abcf57ca6a8456ee7c5fc42a7c2d33e49ffe64476ae4d3a' +
    'c7a217dedc43eb700f35b807b763e9978967ec826369044d87a9f453c3c9bdd4',
  macKey: '92d7b6131b7c2a3ea027156d9b48a09ca86f5428afc54124f0452c34fd32e148',
  confirmS: '0e8b228a4471b5fa83d03abe1eb15f34eaafd4287fdc696ab947f98a4d8af423',
  confirmR: '657b1be7f2327b8e854e135d0691f3475607c65edb564be7eed860316e4dd84c',
  kR2S: '89b67d235a0f92ed854efe45ede308c6c0831b6e48dc1be12559e38c3a8defe8',
  kS2R: '9f081c6dd73e008a1c9c70b6bd42bad353ede9e83d8dcfd54e84db97a4ca95f4'
}

const SID = Buffer.from(V.sid, 'hex')
const YA_SCALAR = Buffer.from(V.ya, 'hex')
const YB_SCALAR = Buffer.from(V.yb, 'hex')

// A length-prefixed concatenation written here, by hand, so that the
// "second way" below does not call the lvCat it is checking.
//
// Only single-byte LEB128 lengths are implemented, and that limitation is
// asserted rather than assumed: every field in this vector is under 128
// bytes, and a field that grew past it would break this encoder loudly
// instead of silently disagreeing with cpace.js's.
function lv (...parts) {
  return Buffer.concat(parts.map((part) => {
    assert.ok(
      part.length < 128,
      `this hand-built encoder only covers single-byte lengths; got ${part.length}`
    )
    return Buffer.concat([Buffer.from([part.length]), part])
  }))
}

test('the capability encodings and associated data match the vector', () => {
  const capsR = encodeCaps(V.capsR)
  const capsS = encodeCaps(V.capsS)
  assert.equal(capsR.toString('utf8'), 'resume,stream')
  assert.equal(capsS.toString('utf8'), 'resume')

  // CI binds the nameplate under a versioned label; ADa/ADb bind the wire
  // version and each side's capabilities. Checked against hand-built byte
  // strings, which is what catches a label typo -- the pinned hex alone
  // would not tell you the label had changed, only that something had.
  assert.equal(hex(channelIdentifier(V.nameplate)), V.CI)
  assert.equal(hex(lv(utf8('quay-v2'), utf8(V.nameplate))), V.CI)

  assert.equal(hex(associatedData(capsR)), V.ADa)
  assert.equal(hex(lv(Buffer.from([VERSION]), capsR)), V.ADa)
  assert.equal(hex(associatedData(capsS)), V.ADb)
  assert.equal(hex(lv(Buffer.from([0x02]), capsS)), V.ADb)

  // ADa and ADb must really differ in this vector, or the swapped-AD
  // mistake it exists to catch would pass.
  assert.notEqual(V.ADa, V.ADb)
})

test('the generator, both public points and the shared K match the vector', () => {
  const CI = channelIdentifier(V.nameplate)
  const PRS = utf8(V.secret)

  // The generator string is the input the whole PAKE hangs off: the
  // password is inside it, padded so it falls in the first SHA-512 block.
  // Pinned because a change here changes every value below it.
  assert.equal(
    hex(generatorString(PRS, CI, SID)).slice(0, 50),
    hex(lv(utf8('CPace255'), PRS)).slice(0, 50) + '67',
    'the generator string opens with lv_cat(DSI, PRS) then the zero padding'
  )

  const g = calculateGenerator(PRS, CI, SID)
  assert.equal(hex(g), V.generator)
  assert.equal(hex(scalarMultVfy(YA_SCALAR, g)), V.Ya)
  assert.equal(hex(scalarMultVfy(YB_SCALAR, g)), V.Yb)

  // BOTH SIDES, and this is the assertion that a vector generated by one
  // implementation can still make meaningfully: K is computed twice, from
  // opposite ends, and Diffie-Hellman's whole claim is that they agree. A
  // mapping that fed different inputs to the two roles would fail here
  // even though every pinned value above would still match.
  const Ya = scalarMultVfy(YA_SCALAR, g)
  const Yb = scalarMultVfy(YB_SCALAR, g)
  assert.equal(hex(scalarMultVfy(YA_SCALAR, Yb)), V.K, 'receiver side')
  assert.equal(hex(scalarMultVfy(YB_SCALAR, Ya)), V.K, 'sender side')
})

test('the transcript matches the vector, and is ordered initiator-first', () => {
  const Ya = Buffer.from(V.Ya, 'hex')
  const Yb = Buffer.from(V.Yb, 'hex')
  const ADa = Buffer.from(V.ADa, 'hex')
  const ADb = Buffer.from(V.ADb, 'hex')

  assert.equal(hex(transcriptIR(Ya, ADa, Yb, ADb)), V.transcript)

  // transcript_ir, not transcript_oc -- permitted only because message
  // order is enforced (the receiver always writes first; PROTOCOL.md
  // section 3.1). Built by hand here so the NESTING is checked and not
  // just the bytes: it is lv_cat(Ya, ADa) followed by lv_cat(Yb, ADb), two
  // separate concatenations, not one lv_cat over four fields.
  assert.equal(hex(Buffer.concat([lv(Ya, ADa), lv(Yb, ADb)])), V.transcript)

  // And it is order-sensitive: swapping the roles must change it, or
  // "_ir" would be meaningless.
  assert.notEqual(hex(transcriptIR(Yb, ADb, Ya, ADa)), V.transcript)
})

test('the ISK, MAC key, both confirmations and both channel keys match the vector', () => {
  const K = Buffer.from(V.K, 'hex')
  const transcript = Buffer.from(V.transcript, 'hex')

  const derived = deriveAll(SID, K, transcript)
  assert.equal(hex(isk(SID, K, transcript)), V.isk)
  assert.equal(hex(derived.isk), V.isk)
  assert.equal(hex(derived.macKey), V.macKey)
  assert.equal(hex(derived.confirmS), V.confirmS)
  assert.equal(hex(derived.confirmR), V.confirmR)
  assert.equal(hex(derived.kR2S), V.kR2S)
  assert.equal(hex(derived.kS2R), V.kS2R)

  // Every derived value must be distinct. Four HKDF calls over one ISK
  // differing only by their info string is exactly the construction where
  // a copy-paste error produces two identical keys, and two identical
  // directional keys would mean a nonce reused on the first frame in each
  // direction (engine/src/channel.js).
  const all = [V.macKey, V.confirmS, V.confirmR, V.kR2S, V.kS2R]
  assert.equal(new Set(all).size, all.length, 'no two derived values may coincide')
})

test('the same derivations, recomputed with node:crypto over hand-built bytes', () => {
  // THE ONLY PART OF THIS FILE THAT IS MORE THAN A PIN. Nothing below
  // calls cpace.js or handshake.js: the byte strings are assembled with
  // the local `lv`, and the primitives are Node's rather than
  // @noble/hashes'. Two independent implementations of SHA-512 and of the
  // length-prefixing therefore have to agree.
  //
  // What this catches that the pinned hex cannot: a wrong info string, a
  // wrong salt (sid, not empty), a confirmation label applied to the wrong
  // role, HMAC over lv_cat(label, transcript) instead of the plain
  // concatenation section 3.2 specifies, or an HKDF length other than 32.
  const K = Buffer.from(V.K, 'hex')
  const transcript = Buffer.from(V.transcript, 'hex')

  // ISK = SHA-512( lv_cat("CPace255_ISK", sid, K) || transcript )
  const iskInput = Buffer.concat([lv(utf8('CPace255_ISK'), SID, K), transcript])
  const iskAgain = crypto.createHash('sha512').update(iskInput).digest()
  assert.equal(hex(iskAgain), V.isk, 'ISK via node:crypto SHA-512')

  // mac_key = HKDF-SHA256(ISK, salt=sid, info="quay-v2:mac", 32)
  const hkdf = (info) => Buffer.from(crypto.hkdfSync('sha256', iskAgain, SID, info, 32))
  assert.equal(hex(hkdf('quay-v2:mac')), V.macKey)
  assert.equal(hex(hkdf('quay-v2:r2s')), V.kR2S)
  assert.equal(hex(hkdf('quay-v2:s2r')), V.kS2R)

  // confirm* = HMAC-SHA256(mac_key, "quay-v2:confirm-?" || transcript).
  // Plain concatenation of the label and the transcript, not lv_cat: the
  // labels are fixed-length and distinct, and section 3.2 writes it with
  // `||`.
  const mac = (label) => crypto
    .createHmac('sha256', hkdf('quay-v2:mac'))
    .update(Buffer.concat([utf8(label), transcript]))
    .digest()
  assert.equal(hex(mac('quay-v2:confirm-s')), V.confirmS)
  assert.equal(hex(mac('quay-v2:confirm-r')), V.confirmR)

  // And the salt really is the sid. An empty salt is the plausible
  // alternative and HKDF accepts it silently, so it is asserted against
  // rather than trusted.
  assert.notEqual(
    hex(Buffer.from(crypto.hkdfSync('sha256', iskAgain, Buffer.alloc(0), 'quay-v2:mac', 32))),
    V.macKey,
    'salt=sid must matter; if this passes, the sid is not reaching HKDF'
  )
})
