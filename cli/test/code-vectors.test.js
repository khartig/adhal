'use strict'

// Frozen input/output pairs for the v2 code format: a typed string to a
// canonical code, to a nameplate and a secret, to a topic and a QR payload.
//
// WHY A SEPARATE FILE FROM code.test.js. That file checks *properties* --
// that parsing is idempotent, that variants agree, that the split is total
// -- by recomputing both sides with the same code under test. That proves
// self-consistency, which is worth having and is not conformance: a module
// that is wrong in the same way twice passes all of it.
//
// The values below are fixed. They are the first of the ad-hal-specific
// vectors PROTOCOL.md section 11 requires, and their job is different in
// two ways:
//
//   1. They regression-lock the derivation. Changing the topic prefix, the
//      word order inside a half, the split index, or the separator all
//      change a digest here and nothing else in the suite would notice --
//      every other test would happily agree with the new derivation.
//      Silently changing the topic derivation is a wire break that presents
//      as ERR_NO_PEER, i.e. as a network problem.
//   2. They are what a second implementation can be checked against
//      without running this one.
//
// HONEST ABOUT WHAT THEY PROVE. Unlike cpace-vectors.test.js -- whose
// values are transcribed from draft-irtf-cfrg-cpace-14 and are therefore an
// external acceptance criterion -- the digests below were generated BY this
// implementation. They cannot show the derivation is the one PROTOCOL.md
// section 2 specifies; only that it has not drifted since it was reviewed
// against section 2 by eye.
//
// So the two claims section 2's derivation actually rests on are checked
// separately rather than left inside the composite digest:
//
//   - the hash is BLAKE2b-256, checked against the PUBLISHED digest of
//     "abc". That value is external to this repo, so it is evidence and
//     not a pin.
//   - the input is "adhal-v2:topic" || nameplate, literal, no separator,
//     checked by building that byte string here and hashing it directly
//     instead of calling topicFromNameplate.
//
// Together those are what a pinned digest cannot distinguish: a changed
// hash function and a changed input construction would both present as
// "the vectors need regenerating".

const test = require('node:test')
const assert = require('node:assert/strict')

const {
  parseCode,
  splitCode,
  resolveCode,
  topicFromNameplate,
  blake2b256,
  encodeQrPayload,
  TOPIC_PREFIX
} = require('@ad-hal/engine')

// BLAKE2b-256 of "abc", from the BLAKE2 reference vectors. Not computed
// here and not chosen by this project: it is the external check that the
// function the topic is built on is the one section 2 names. Node's own
// crypto cannot supply a second opinion -- it ships blake2b512 and
// blake2s256, and BLAKE2b-256 is not blake2b512 truncated, because the
// digest length is mixed into the initialisation vector.
const BLAKE2B_256_OF_ABC =
  'bddd813c634239723171ef3fee98579b94964e3bb1cb3e427262c8c068d52319'

// Each vector: what a human or a camera might supply, and everything that
// must fall out of it. `topic` is BLAKE2b-256("adhal-v2:topic" || nameplate),
// hex.
const VECTORS = [
  {
    // Also the first five words of the list, so this doubles as the
    // boundary vector an off-by-one in wordlist.js would move.
    what: 'the canonical example from PROTOCOL.md section 2',
    input: 'acid-acorn-acre-acts-afar',
    code: 'acid-acorn-acre-acts-afar',
    nameplate: 'acid-acorn',
    secret: 'acre-acts-afar',
    topic: 'd6f1423db950f2573d0a5db14f43a2e377099bd2acb38cc2c239552fafcdceb8',
    payload: 'ADHAL2:ACID-ACORN-ACRE-ACTS-AFAR'
  },
  {
    // The scanned form of the vector above. It must land on the same topic
    // and the same secret, or scanning and typing are two paths rather than
    // one -- which is the decision the QR payload exists to make provable.
    what: 'the same code as a scanned QR payload',
    input: 'ADHAL2:ACID-ACORN-ACRE-ACTS-AFAR',
    code: 'acid-acorn-acre-acts-afar',
    nameplate: 'acid-acorn',
    secret: 'acre-acts-afar',
    topic: 'd6f1423db950f2573d0a5db14f43a2e377099bd2acb38cc2c239552fafcdceb8',
    payload: 'ADHAL2:ACID-ACORN-ACRE-ACTS-AFAR'
  },
  {
    // Mangled separators and mixed case, which is what a code read off
    // another screen and retyped actually looks like.
    what: 'the same code pasted out of a chat client',
    input: '  Acid_acorn.acre  acts--afar ',
    code: 'acid-acorn-acre-acts-afar',
    nameplate: 'acid-acorn',
    secret: 'acre-acts-afar',
    topic: 'd6f1423db950f2573d0a5db14f43a2e377099bd2acb38cc2c239552fafcdceb8',
    payload: 'ADHAL2:ACID-ACORN-ACRE-ACTS-AFAR'
  },
  {
    // The tail of the list, for the same reason.
    what: 'the tail of the word list',
    input: 'zero-zesty-zippy-zone-zoom',
    code: 'zero-zesty-zippy-zone-zoom',
    nameplate: 'zero-zesty',
    secret: 'zippy-zone-zoom',
    topic: '81df9e2b52944e117a5eab83f0aaeea8a3eb4079e4c8ec1a0a168d8ff91da84d',
    payload: 'ADHAL2:ZERO-ZESTY-ZIPPY-ZONE-ZOOM'
  },
  {
    // Five five-letter words: the longest payload the generator can emit,
    // and the one the QR size table is indexed on (35 characters).
    what: 'the longest possible code',
    input: 'acorn-affix-agent-agile-aging',
    code: 'acorn-affix-agent-agile-aging',
    nameplate: 'acorn-affix',
    secret: 'agent-agile-aging',
    topic: '944e50f3d68e755bed43dc38fec0bdd52ed9fed527dd89a835a0cf9a0f068d6c',
    payload: 'ADHAL2:ACORN-AFFIX-AGENT-AGILE-AGING'
  },
  {
    // A repeated word is a legitimate draw (see generateCode), and it is
    // the case where a split that deduplicated or re-sorted would still
    // look plausible.
    what: 'one word repeated five times',
    input: 'acid-acid-acid-acid-acid',
    code: 'acid-acid-acid-acid-acid',
    nameplate: 'acid-acid',
    secret: 'acid-acid-acid',
    topic: 'cd07125af48f5e3340008b1ac0abe53d9b89dcc321e317e1c8e126aab16f5d73',
    payload: 'ADHAL2:ACID-ACID-ACID-ACID-ACID'
  }
]

test('every code vector reproduces its canonical form, halves, topic and payload', () => {
  for (const v of VECTORS) {
    assert.equal(parseCode(v.input), v.code, `code for ${v.what}`)
    assert.deepEqual(
      splitCode(v.input),
      { nameplate: v.nameplate, secret: v.secret },
      `split for ${v.what}`
    )
    assert.equal(encodeQrPayload(v.input), v.payload, `payload for ${v.what}`)

    const resolved = resolveCode(v.input)
    assert.equal(resolved.kind, 'words')
    assert.equal(resolved.code, v.code)
    assert.equal(resolved.nameplate, v.nameplate)
    assert.equal(resolved.secret, v.secret)
    assert.equal(resolved.topic.toString('hex'), v.topic, `topic for ${v.what}`)
    assert.equal(
      topicFromNameplate(v.nameplate).toString('hex'),
      v.topic,
      `topic from the nameplate alone for ${v.what}`
    )
  }
})

test('the topic hash is BLAKE2b-256, against the published digest', () => {
  // EXTERNAL EVIDENCE, and the only assertion in this file that is not
  // this implementation agreeing with itself. hypercore-crypto's `hash` is
  // documented as BLAKE2b-256; this is the check that it is, so that a
  // dependency which silently changed algorithm would fail here rather
  // than quietly move every topic in the network.
  assert.equal(blake2b256(Buffer.from('abc', 'utf8')).toString('hex'), BLAKE2B_256_OF_ABC)
  assert.equal(blake2b256(Buffer.alloc(0)).length, 32, 'a 32-byte digest, not a truncated 64')
})

test('each vector topic is the hash of the spec byte string, built explicitly', () => {
  // topicFromNameplate is deliberately NOT called here. The byte string is
  // assembled the way PROTOCOL.md section 2 writes it -- the prefix
  // concatenated with the nameplate, literal, no separator and no length
  // prefix -- and hashed directly.
  //
  // This is what the pinned digests above cannot check: an extra ':', a
  // length prefix, a trailing NUL, or hashing the whole code instead of
  // the nameplate would each produce a self-consistent set of vectors and
  // fail only here. The last of those is the one that matters, because it
  // is v1's behaviour and it is what v2 exists to stop.
  for (const v of VECTORS) {
    const built = Buffer.concat([
      Buffer.from('adhal-v2:topic', 'utf8'),
      Buffer.from(v.nameplate, 'utf8')
    ])
    assert.equal(blake2b256(built).toString('hex'), v.topic, `explicit byte string for ${v.what}`)
    assert.equal(
      topicFromNameplate(v.nameplate).toString('hex'),
      blake2b256(built).toString('hex'),
      `topicFromNameplate must hash exactly those bytes for ${v.what}`
    )
  }

  // And the prefix the engine uses really is that string, so the two
  // computations are not agreeing by coincidence over a different constant.
  assert.equal(TOPIC_PREFIX, 'adhal-v2:topic')

  // The secret must not be reachable from the topic, stated as the
  // negative it is: hashing the whole code gives a different digest, so no
  // vector's topic commits to its secret.
  for (const v of VECTORS) {
    const wholeCode = blake2b256(Buffer.from(`adhal-v2:topic${v.code}`, 'utf8')).toString('hex')
    assert.notEqual(wholeCode, v.topic, `the topic must not commit to the whole code (${v.what})`)
  }
})

test('the vectors cover the cases a wrong split would still satisfy', () => {
  // A meta-assertion, because a vector file is only as good as its spread
  // and "add a vector" is easy to forget. Each clause below names a
  // plausible implementation error and asserts that some vector would catch
  // it.
  const bySecret = new Set(VECTORS.map((v) => v.secret))
  const byNameplate = new Set(VECTORS.map((v) => v.nameplate))
  assert.ok(byNameplate.size >= 4, 'several distinct nameplates, or a fixed topic would pass')
  assert.ok(bySecret.size >= 4, 'several distinct secrets')

  // Two vectors that share a topic but arrive in different input styles:
  // catches a normalisation that is applied to one path and not the other.
  const sharing = VECTORS.filter((v) => v.nameplate === 'acid-acorn')
  assert.ok(new Set(sharing.map((v) => v.input)).size >= 3, 'at least three input styles for one code')

  // A repeated-word vector: catches a split that deduplicates.
  assert.ok(VECTORS.some((v) => new Set(v.code.split('-')).size === 1), 'a repeated-word code')

  // A vector whose words are not in list order within a half: catches a
  // split that sorts. 'zippy-zone-zoom' is in order, so this leans on the
  // pasted vector's halves staying positional -- asserted directly.
  assert.equal(splitCode('afar-acts-acre-acorn-acid').nameplate, 'afar-acts',
    'the split must be positional, never sorted')
})
